"""
Optimizer-comparison engine (Step 3.1).

Demonstrates that the SCAL inverse problem is ill-posed by running the
SAME noisy dataset through several independent fits and showing that
they land on different parameter sets at statistically indistinguishable
objective values.

Two kinds of evidence, produced in one run set:

    multi-start LM  N independent Levenberg-Marquardt fits from
                    Latin-hypercube-sampled starting points. This is the
                    stronger evidence, because every run uses the same
                    optimizer on the same data — any spread in the
                    answers is a property of the problem, not of the
                    algorithm.

    DE control      one Differential Evolution run on the same data,
                    showing that a global method does not rescue the
                    situation. Optional, because it is expensive.

Why noise matters
-----------------
A noise-free synthetic dataset generated by the same solver at the same
grid has a unique global minimum at exactly zero, and any optimizer
started in the right basin will find it (verified 19 Oct 2026: LM
recovered all four Corey parameters exactly). That proves the fitting
machinery works; it says nothing about identifiability. Ill-posedness
only becomes visible once the data cannot distinguish between candidate
parameter sets, which is what the noise level controls here.

The noise realisation is generated ONCE and shared by every run in the
set. Re-drawing it per run would measure noise variation rather than
optimizer behaviour.

Reporting
---------
Raw SSE in mbar^2 is uninterpretable on its own. Everything is also
reported as a reduced chi-squared,

    chi2_red = SSE / (sigma^2 * (n_points - n_free))

which is ~1.0 when a fit is as good as the noise allows. Several runs
at chi2_red ~ 1 with visibly different kr curves is the whole argument.

Pure NumPy / SciPy / pandas; no Streamlit.
"""

import copy
import time

import numpy as np
import pandas as pd
from scipy.stats import qmc

from utils.kr_models import get_model_class
from utils.twophase_inverse import fit_kr


# ── Input preparation ──────────────────────────────────────────────────────
def prepare_inputs(tp_inputs, force_pc_off=True, n_cells=None):
    """
    Return a copy of tp_inputs adjusted for comparison runs.

    Capillary pressure is forced off by default. The degeneracy being
    demonstrated does not depend on Pc, and each forward call with
    Skjaeveland Pc costs roughly 5x the no-Pc call at the same grid —
    enough to push a multi-run set past the hosted execution wall.
    """
    inp = copy.deepcopy(tp_inputs)
    if force_pc_off:
        inp["pc"]["enabled"] = False
    if n_cells is not None:
        inp["numerical"]["N_cells"] = int(n_cells)
    return inp


# ── Synthetic data with a single shared noise realisation ──────────────────
def generate_synthetic_data(inp, n_points=60, noise_pct=1.0, seed=0):
    """
    Run the forward model at the truth parameters in `inp`, subsample to
    `n_points` measurement times, and add one Gaussian noise realisation.

    Noise is additive with CONSTANT sigma, set as a percentage of the
    peak dP. That models a pressure transducer with fixed instrument
    precision, and it keeps the chi-squared interpretation clean
    (proportional noise would need a weighted objective, which fit_kr
    does not implement).

    Returns dict:
        t_min, dp_clean, dp_noisy, sigma_mbar, n_points,
        forward_time_s, truth_params, results
    """
    from utils.twophase_solver import run_forward

    t0 = time.perf_counter()
    res = run_forward(inp)
    forward_time_s = time.perf_counter() - t0

    t_full  = np.asarray(res["t_min"], dtype=float)
    dp_full = np.asarray(res["dP_mbar"], dtype=float)

    idx = np.unique(
        np.linspace(0, len(t_full) - 1, int(n_points)).astype(int)
    )
    t_min    = t_full[idx]
    dp_clean = dp_full[idx]

    sigma = float(noise_pct) / 100.0 * float(np.nanmax(dp_full))
    rng = np.random.default_rng(int(seed))
    dp_noisy = (dp_clean + rng.normal(0.0, sigma, size=dp_clean.shape)
                if sigma > 0.0 else dp_clean.copy())

    return {
        "t_min":          t_min,
        "dp_clean":       dp_clean,
        "dp_noisy":       dp_noisy,
        "sigma_mbar":     sigma,
        "n_points":       int(len(t_min)),
        "forward_time_s": forward_time_s,
        "truth_params":   dict(inp["kr"]["params"]),
        "results":        res,
    }


# ── Starting-point sampling ────────────────────────────────────────────────
def sample_starts(model_cls, free_indices, n_starts, seed=0):
    """
    Latin-hypercube sample of starting points across the free parameters'
    bounds, drawn in log space for parameters the model flags as
    multi-decade. Returns a list of physical-parameter lists, one per
    start, in free_indices order.

    None of the starts is seeded at truth. A run that begins at the
    answer proves nothing.
    """
    lows, highs, is_log = [], [], []
    for i in free_indices:
        name = model_cls.parameter_names[i]
        lo, hi = model_cls.parameter_bounds[name]
        lg = bool(model_cls.log_space_params[name])
        lows.append(np.log(lo) if lg else lo)
        highs.append(np.log(hi) if lg else hi)
        is_log.append(lg)

    sampler = qmc.LatinHypercube(d=len(free_indices), seed=int(seed))
    scaled = qmc.scale(sampler.random(int(n_starts)),
                       np.array(lows), np.array(highs))

    starts = []
    for row in scaled:
        starts.append([
            float(np.exp(v)) if is_log[j] else float(v)
            for j, v in enumerate(row)
        ])
    return starts


# ── Run set ────────────────────────────────────────────────────────────────
def _chi2_red(sse, sigma, n_points, n_free):
    dof = max(n_points - n_free, 1)
    if sigma <= 0.0:
        return float("nan")
    return float(sse) / (sigma ** 2 * dof)


def run_comparison(inp, data, fit_mask, n_starts=5, max_iter=300,
                   include_de=False, de_max_iter=300, seed=0,
                   on_run=None):
    """
    Run the full comparison set against one shared dataset.

    Parameters
    ----------
    inp : dict
        Prepared tp_inputs. `inp["kr"]["params"]` holds the TRUTH values;
        they are used verbatim for any parameter held fixed by fit_mask,
        and overwritten by the sampled start for free parameters.
    data : dict
        Output of generate_synthetic_data.
    fit_mask : list[bool]
        Which parameters are free, in model parameter_names order.
    n_starts : int
        Number of independent LM fits.
    include_de : bool
        Add one Differential Evolution run on the same data.
    on_run : callable or None
        on_run(index, total, label) before each run, for progress.

    Returns list of run dicts, each with:
        label, optimizer, start_params, fitted_params, sse, chi2_red,
        n_calls, converged, message, wall_s
    """
    model_cls   = get_model_class(inp["kr"]["model"])
    param_names = list(model_cls.parameter_names)
    truth       = dict(inp["kr"]["params"])

    free_indices = [i for i, m in enumerate(fit_mask) if m]
    n_free = len(free_indices)
    if n_free == 0:
        raise ValueError("At least one parameter must be free to compare.")

    starts = sample_starts(model_cls, free_indices, n_starts, seed=seed)
    total = int(n_starts) + (1 if include_de else 0)
    runs = []

    for k, start in enumerate(starts):
        label = f"LM #{k + 1}"
        if on_run is not None:
            on_run(k + 1, total, label)

        run_inputs = copy.deepcopy(inp)
        params = dict(truth)
        for j, i in enumerate(free_indices):
            params[param_names[i]] = start[j]
        run_inputs["kr"]["params"] = params

        t0 = time.perf_counter()
        try:
            fit = fit_kr(
                run_inputs, data["t_min"], data["dp_noisy"],
                fit_mask=fit_mask, max_iter=int(max_iter),
                on_iter=None, optimizer_name="Levenberg-Marquardt",
            )
        except Exception as e:                      # keep the set alive
            runs.append({
                "label": label, "optimizer": "Levenberg-Marquardt",
                "start_params": dict(params), "fitted_params": None,
                "sse": float("nan"), "chi2_red": float("nan"),
                "n_calls": 0, "converged": False,
                "message": f"FAILED: {e}",
                "wall_s": time.perf_counter() - t0,
            })
            continue

        runs.append({
            "label": label, "optimizer": "Levenberg-Marquardt",
            "start_params":  dict(params),
            "fitted_params": dict(fit["fitted_params"]),
            "sse":      float(fit["sse"]),
            "chi2_red": _chi2_red(fit["sse"], data["sigma_mbar"],
                                  data["n_points"], n_free),
            "n_calls":   int(fit["n_calls"]),
            "converged": bool(fit["converged"]),
            "message":   fit["message"],
            "wall_s":    time.perf_counter() - t0,
            "sim_t":     np.asarray(fit["results"]["t_min"], dtype=float),
            "sim_dp":    np.asarray(fit["results"]["dP_mbar"], dtype=float),
        })

    if include_de:
        label = "DE control"
        if on_run is not None:
            on_run(total, total, label)
        run_inputs = copy.deepcopy(inp)
        run_inputs["kr"]["params"] = dict(truth)   # DE ignores the start
        t0 = time.perf_counter()
        try:
            fit = fit_kr(
                run_inputs, data["t_min"], data["dp_noisy"],
                fit_mask=fit_mask, max_iter=int(de_max_iter),
                on_iter=None, optimizer_name="Differential Evolution",
            )
            runs.append({
                "label": label, "optimizer": "Differential Evolution",
                "start_params":  None,
                "fitted_params": dict(fit["fitted_params"]),
                "sse":      float(fit["sse"]),
                "chi2_red": _chi2_red(fit["sse"], data["sigma_mbar"],
                                      data["n_points"], n_free),
                "n_calls":   int(fit["n_calls"]),
                "converged": bool(fit["converged"]),
                "message":   fit["message"],
                "wall_s":    time.perf_counter() - t0,
                "sim_t":     np.asarray(fit["results"]["t_min"],
                                        dtype=float),
                "sim_dp":    np.asarray(fit["results"]["dP_mbar"],
                                        dtype=float),
            })
        except Exception as e:
            runs.append({
                "label": label, "optimizer": "Differential Evolution",
                "start_params": None, "fitted_params": None,
                "sse": float("nan"), "chi2_red": float("nan"),
                "n_calls": 0, "converged": False,
                "message": f"FAILED: {e}",
                "wall_s": time.perf_counter() - t0,
            })

    return runs


# ── Reporting ──────────────────────────────────────────────────────────────
def results_table(runs, truth_params, param_names, fit_mask):
    """
    Tidy one-row-per-run DataFrame: label, chi2_red, SSE, calls,
    converged, and the fitted value of every free parameter. A final
    TRUTH row is appended for reference.
    """
    free_names = [n for n, m in zip(param_names, fit_mask) if m]
    rows = []
    for r in runs:
        row = {
            "run":       r["label"],
            "chi2_red":  r["chi2_red"],
            "SSE_mbar2": r["sse"],
            "calls":     r["n_calls"],
            "converged": r["converged"],
        }
        fp = r["fitted_params"] or {}
        for n in free_names:
            row[n] = fp.get(n, float("nan"))
        rows.append(row)

    truth_row = {"run": "TRUTH", "chi2_red": np.nan, "SSE_mbar2": np.nan,
                 "calls": np.nan, "converged": True}
    for n in free_names:
        truth_row[n] = truth_params[n]
    rows.append(truth_row)
    return pd.DataFrame(rows)


def spread_summary(runs, truth_params, param_names, fit_mask,
                   chi2_tol=None):
    """
    Per-parameter spread across the runs that actually fitted the data.

    `chi2_tol` restricts the summary to runs whose chi2_red is at or
    below that value — the honest comparison set, since a run that fit
    badly is not evidence of degeneracy, just of a failed fit. Default
    is no filter.

    Returns DataFrame with truth, min, max, spread as a percentage of
    truth, and the parameter bound width for context.
    """
    free_names = [n for n, m in zip(param_names, fit_mask) if m]
    good = [r for r in runs if r["fitted_params"] is not None]
    if chi2_tol is not None:
        good = [r for r in good
                if np.isfinite(r["chi2_red"]) and r["chi2_red"] <= chi2_tol]

    rows = []
    for n in free_names:
        vals = np.array([r["fitted_params"][n] for r in good], dtype=float)
        if vals.size == 0:
            continue
        t = float(truth_params[n])
        lo, hi = float(np.min(vals)), float(np.max(vals))
        rows.append({
            "parameter":      n,
            "truth":          t,
            "min":            lo,
            "max":            hi,
            "spread_pct_of_truth": (
                (hi - lo) / abs(t) * 100.0 if t != 0 else np.nan
            ),
            "n_runs":         int(vals.size),
        })
    return pd.DataFrame(rows)


def attach_kr_curves(runs, inp):
    """
    Compute the fitted kr curves for each successful run and attach them
    under the key "kr". Also returns the truth curves.
    """
    from utils.twophase import kr_curves

    for r in runs:
        if r["fitted_params"] is None:
            r["kr"] = None
            continue
        ci = copy.deepcopy(inp)
        ci["kr"]["params"] = dict(r["fitted_params"])
        r["kr"] = kr_curves(ci)

    return kr_curves(copy.deepcopy(inp))